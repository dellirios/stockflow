'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { applyPrinterGeometry, applyPrinterSettings } = require('../src/services/printerGeometry');
const current = fs.readFileSync(path.join(__dirname, '../src/services/printerService.js'), 'utf8');
const originalTemplate = fs.readFileSync(path.join(__dirname, 'fixtures/original-default-template.zpl'), 'utf8');
const template = source => source.match(/const DEFAULT_TEMPLATE = `([\s\S]*?)`;/)[1];
const original = template(current);
assert.equal(original, originalTemplate, 'Original label layout must remain identical');
const printer = { geometria: { largura_mm: 60, altura_mm: 60, resolucao_dpi: 203, offset_horizontal_mm: 4 } };
const output = applyPrinterGeometry(original, printer);
assert.match(output, /\^PW480\n\^LL480\n\^LH32,0\n\^LS0/);
const withoutGeometry = zpl => zpl.replace(/\^(PW|LL|LS)-?\d+|\^LH\d+,\d+/g, '').replace(/\s/g, '');
assert.equal(withoutGeometry(output), withoutGeometry(original), 'All field commands must be preserved');
assert.equal(applyPrinterGeometry(original, {}), original, 'Other printers must remain unchanged');
assert.equal((applyPrinterGeometry(original + original, printer).match(/\^LH32,0/g) || []).length, 2);
assert.match(applyPrinterGeometry('^XA^LH9,17^FO16,34^FDTEST^FS^XZ', printer), /\^LH32,17/);
assert.equal(applyPrinterGeometry(output, printer), output, 'Geometry must not accumulate');
assert.match(applyPrinterGeometry(original, { geometria: { ...printer.geometria, offset_horizontal_mm: -4 } }), /\^LH0,0\n\^LS32/);
assert.throws(() => applyPrinterGeometry(original, { geometria: { ...printer.geometria, resolucao_dpi: 0 } }));
assert.throws(() => applyPrinterGeometry(original, { geometria: { ...printer.geometria, offset_horizontal_mm: 60 } }));
console.log('Printer geometry checks passed; original layout preserved.');
const cool = applyPrinterSettings(original, { ...printer, intensidade: 8 });
assert.match(cool, /^~SD08\n\^XA\n\^MD0/);
assert.equal(cool.replace('~SD08\n', '').replace(/\n\^MD0/g, ''), output);
assert.equal(applyPrinterSettings(original, {}), original);
assert.throws(() => applyPrinterSettings(original, { intensidade: 31 }));
console.log('Printer intensity checks passed.');
